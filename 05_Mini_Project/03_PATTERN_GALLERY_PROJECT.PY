# PATTERN GALLERY :

# INCREASING PATTERN:

for i in range(1,6):
    for j in range(1,i+1):
        print("*",end=" ")
    print()

# DECREASING PATTERN:

for k in range(4,0,-1):
    for l in range(1,k+1):
        print("*",end=" ")
    print()

# NUMBER TRIANGLE PATTERN :

for m in range(1,6):
    for n in range(1,m+1):
        print(n,end=" ")
    print()